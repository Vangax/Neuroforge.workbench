# Provenance -> a standalone Python script that reproduces the derivative.
#
# This is the answer to the only question that matters when someone else reads your
# result: "what did you actually do to the data?" A provenance list is a record; a
# script is a *test* of that record — anyone can run it, on the original file, with
# nothing but MNE installed, and get the same numbers back.
from __future__ import annotations

import platform
from datetime import datetime, timezone

import mne
import numpy as np

HEADER = '''"""
Reproduction script for: {label}
Generated by NeuroForge {version} on {when}

Source recording : {source}
Format           : {fmt}
Sampling rate    : {sfreq:g} Hz
Channels         : {n_channels}
Duration         : {duration:.1f} s

Recorded with    : MNE-Python {mne_v}, NumPy {np_v}, Python {py_v} ({plat})

Run it:
    pip install mne numpy
    python {filename}

This script is generated from the dataset's provenance log — the ordered list of
operations NeuroForge actually applied. It is not a template or an approximation.
If a step is missing here, it was not applied to your data.
"""
import mne
import numpy as np

'''

FOOTER = '''
# --------------------------------------------------------------------------- #
# Verification
# --------------------------------------------------------------------------- #
# NeuroForge recorded this fingerprint for the processed data. If your run prints
# the same value, you have reproduced the derivative exactly.
EXPECTED_HASH = "{expected}"

import hashlib
actual = hashlib.sha256(raw.get_data().tobytes()).hexdigest()[:16]
print(f"reproduction hash : {{actual}}")
print(f"expected          : {{EXPECTED_HASH}}")
print("MATCH" if actual == EXPECTED_HASH else
      "DIFFERENT — see the note below")

# A mismatch is not automatically a problem. ICA (FastICA) is initialised randomly;
# NeuroForge pins random_state=42, but different MNE/NumPy versions can still land on
# a different but equally valid decomposition. Filtering and referencing are
# deterministic and should match to the bit.
'''

#: How each pipeline op is written out. Keep these in step with pipeline.run_pipeline —
#: a script that does not match the engine is worse than no script at all.
_READERS = {
    ".edf": "mne.io.read_raw_edf", ".bdf": "mne.io.read_raw_bdf",
    ".gdf": "mne.io.read_raw_gdf", ".vhdr": "mne.io.read_raw_brainvision",
    ".cnt": "mne.io.read_raw_cnt", ".set": "mne.io.read_raw_eeglab",
    ".fif": "mne.io.read_raw_fif", ".mff": "mne.io.read_raw_egi",
    ".nxe": "mne.io.read_raw_nihon",
}


def _reader_for(path: str | None) -> str:
    if not path:
        return "mne.io.read_raw"
    low = path.lower()
    for ext, fn in _READERS.items():
        if low.endswith(ext):
            return fn
    return "mne.io.read_raw"


def _emit(op: str, p: dict) -> list[str]:
    """One provenance step -> the lines of Python that perform it."""
    if op in ("prep:reference", "reference"):
        if p.get("mode", "average") == "average":
            return ['raw.set_eeg_reference("average", projection=False)']
        return [f'raw.set_eeg_reference([{p.get("channel", "Cz")!r}])']

    if op in ("prep:filter", "filter"):
        return [f'raw.filter({p.get("l_freq")!r}, {p.get("h_freq")!r})']

    if op in ("prep:notch", "notch"):
        f = float(p.get("freq", 50))
        return [f"nyq = raw.info['sfreq'] / 2",
                f"raw.notch_filter([{f:g} * k for k in range(1, 5) if {f:g} * k < nyq])"]

    if op in ("prep:resample", "resample"):
        return [f'raw.resample({float(p.get("sfreq", 128)):g})']

    if op in ("prep:detect_bads", "detect_bads"):
        return ["# NeuroForge's detector (robust variance + neighbour correlation on a",
                "# high-passed copy). The channels it selected are listed below, so this",
                "# script does not depend on reimplementing it.",
                "raw.info['bads'] = DETECTED_BADS"]

    if op in ("prep:interpolate", "interpolate"):
        return ["if raw.info['bads']:",
                "    raw.interpolate_bads(reset_bads=True)"]

    if op in ("prep:ica", "ica"):
        return [f"ica = mne.preprocessing.ICA(n_components={int(p.get('n_components', 15))}, "
                f"method={p.get('method', 'fastica')!r},",
                "                             max_iter='auto', random_state=42)",
                "ica.fit(raw)",
                "ica.exclude = ICA_EXCLUDED   # components NeuroForge identified as ocular",
                "ica.apply(raw)"]

    if op in ("edit:crop", "crop"):
        return [f'raw.crop(tmin={float(p.get("tmin", 0)):g}, tmax={float(p.get("tmax", 0)):g})']

    if op in ("edit:montage", "montage"):
        return [f'raw.set_montage({p.get("montage", "standard_1005")!r}, on_missing="ignore")']

    if op in ("edit:channels", "channels"):
        lines = []
        if p.get("drop"):
            lines.append(f'raw.drop_channels({list(p["drop"])!r})')
        if p.get("rename"):
            lines.append(f'raw.rename_channels({dict(p["rename"])!r})')
        if p.get("bads") is not None:
            lines.append(f'raw.info["bads"] = {list(p["bads"])!r}')
        return lines or [f"# {op}: nothing to replay"]

    return [f"# {op}({p}) — recorded in provenance, not reproducible as a raw-level step"]


def build_script(nd, *, filename: str = "reproduce.py") -> str:
    """Render the dataset's provenance as a runnable script."""
    from . import report as _report

    src = nd.source_path
    prov = list(nd.provenance)
    pipeline = (nd.extra or {}).get("pipeline") or []

    out = [HEADER.format(
        label=nd.entities.label(),
        version=(nd.extra or {}).get("neuroforge_version", "0.2.0"),
        when=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        source=src or "(not a file — generated or derived in-session)",
        fmt=nd.source_format, sfreq=nd.sfreq, n_channels=nd.n_channels,
        duration=nd.duration, mne_v=mne.__version__, np_v=np.__version__,
        py_v=platform.python_version(), plat=platform.system(), filename=filename,
    )]

    # Constants the script needs but cannot recompute deterministically.
    # Read them from the pipeline record, not from the final raw: `interpolate`
    # clears info["bads"] on the way out, so by the end the list is empty.
    bads: list[str] = []
    ica_excluded: list[int] = []
    for s in pipeline:
        if s.get("op") == "detect_bads":
            bads = list(s.get("detected", []))
        elif s.get("op") == "ica":
            ica_excluded = list(s.get("excluded", []))
    if not bads:
        bads = list(nd.raw.info.get("bads") or [])
    out.append(f"DETECTED_BADS = {bads!r}")
    out.append(f"ICA_EXCLUDED  = {ica_excluded!r}")
    out.append("")

    def rule(text: str) -> str:
        head = f"# --- {text} "
        return head + "-" * max(3, 78 - len(head))

    if src:
        out += [rule("1. load the original recording"),
                f"SOURCE = r{src!r}",
                f"raw = {_reader_for(src)}(SOURCE, preload=True)",
                ""]
    else:
        out += [rule("1. load the original recording"),
                "# This dataset was generated in-session (synthetic or a sample), so there is",
                "# no source file to reload. Point `raw` at your own recording to replay the",
                "# same pipeline on it.",
                "raw = mne.io.read_raw_fif('YOUR_RECORDING.fif', preload=True)",
                ""]

    # Channel auto-detection happens at load time, before any pipeline step. Leaving
    # it out would make the script analyse every state channel the file calls "EEG" —
    # a silently different recording that happens to run without error.
    det = (nd.extra or {}).get("channel_detection") or {}
    if det.get("auto_detected") and src:
        out.append(rule("1b. channel identification (applied on load)"))
        out.append(f"# {det.get('n_eeg', 0)} real EEG channels among {det.get('n_total', 0)}; "
                   f"{det.get('n_demoted', 0)} were state/marker channels the file mislabels as EEG.")
        if det.get("rename"):
            out.append(f"raw.rename_channels({det['rename']!r})")
        if det.get("retypes"):
            out.append(f"raw.set_channel_types({det['retypes']!r})")
        if det.get("montage"):
            out.append(f"raw.set_montage({det['montage']!r}, on_missing='ignore', match_case=False)")
        out.append("")

    steps = [s for s in prov if s.op.startswith(("prep:", "edit:"))]
    if steps:
        out.append(rule("2. the pipeline, in the order it was applied"))
        for i, s in enumerate(steps, 1):
            label = s.op.split(":", 1)[-1]
            out.append(f"# {i:02d}. {label}")
            out += _emit(s.op, s.params or {})
            out.append("")
    else:
        out += [rule("2. pipeline"),
                "# No preprocessing was applied — this is the recording as it was loaded.",
                ""]

    out.append(rule("3. what you now have"))
    out.append('print(raw.info)')
    out.append('print(f"{len(raw.ch_names)} channels, {raw.times[-1]:.1f} s "')
    out.append('      f"at {raw.info[\'sfreq\']:g} Hz")')

    out.append(FOOTER.format(expected=_report.repro_hash(nd)))
    return "\n".join(out)
